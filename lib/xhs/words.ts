/** hard = 不改就别发；soft = 建议改，用户自己决定 */
export type Severity = 'hard' | 'soft';

export type IssueKind =
  | 'diversion'
  | 'medical'
  | 'absolute'
  | 'industry'
  | 'filler'
  | 'greeting';

export interface WordTable {
  kind: IssueKind;
  label: string;
  severity: Severity;
  /** 一句话说清这类词为什么要改 */
  why: string;
  /** 改写手法。这句会原样进提示词，是模型唯一拿到的「怎么改」 */
  recipe: string;
  words: readonly string[];
  /** 行业名，只有 industry 有 */
  industry?: string;
}

